export function filterMesses(messes, { search = "", diet = "all", budget = 6000, mealPlan = "all", minRating = 0, maxDistance = 15 }) {
  return messes.filter(mess => {
    // Search query
    if (search.trim()) {
      const q = search.toLowerCase();
      const match = mess.name.toLowerCase().includes(q) ||
        mess.area.toLowerCase().includes(q) ||
        mess.address.toLowerCase().includes(q) ||
        mess.cuisine_tags.some(t => t.toLowerCase().includes(q)) ||
        mess.description.toLowerCase().includes(q);
      if (!match) return false;
    }

    // Diet filter
    if (diet !== "all") {
      if (diet === "veg" && mess.diet_type !== "veg" && mess.diet_type !== "jain") return false;
      if (diet === "jain" && mess.diet_type !== "jain") return false;
      if (diet === "both" && mess.diet_type !== "both") return false;
    }

    // Budget filter (monthly)
    if (mess.monthly_price > budget) return false;

    // Rating filter
    if (minRating > 0 && mess.average_rating < minRating) return false;

    // Distance filter
    if (maxDistance && mess.distance_km > maxDistance) return false;

    return true;
  });
}
